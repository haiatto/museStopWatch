"""Make the mini-app symbol table and the SDK's link-check stub.

    .venv\\Scripts\\python.exe tools\\gen_msw_exports.py

Reads sdk/exports.list and the msw_* prototypes of
muse-gadget-sdk/esp32/components/miniapp/include/msw_app.h. Writes
  muse-gadget-sdk/esp32/components/miniapp/msw_app_exports.c  (firmware)
  sdk/stub/msw_stub.c                                         (SDK)
Run it after changing either input, then build the firmware.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "muse-gadget-sdk", "esp32", "components", "miniapp", "include", "msw_app.h")
LIST = os.path.join(ROOT, "sdk", "exports.list")
OUT_FW = os.path.join(ROOT, "muse-gadget-sdk", "esp32", "components", "miniapp", "msw_app_exports.c")
OUT_STUB = os.path.join(ROOT, "sdk", "stub", "msw_stub.c")


def read_list():
    entries = []  # (exported name, implementation, is_data)
    for n, raw in enumerate(open(LIST, encoding="utf-8"), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        data = line.startswith("data ")
        if data:
            line = line[5:].strip()
        if "=" in line:
            name, impl = (p.strip() for p in line.split("=", 1))
        else:
            name = impl = line
        if not re.fullmatch(r"[A-Za-z_]\w*", name) or not re.fullmatch(r"[A-Za-z_]\w*", impl):
            sys.exit(f"{LIST}:{n}: bad entry {raw.strip()!r}")
        entries.append((name, impl, data))
    return entries


def header_functions():
    text = open(HEADER, encoding="utf-8").read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    names = re.findall(r"\b(msw_\w+)\s*\(", text)
    seen, out = set(), []
    for name in names:
        if name not in seen and not name.endswith("_cb"):
            seen.add(name)
            out.append(name)
    return out


def main():
    entries = [(f, f, False) for f in header_functions()] + read_list()
    names = [e[0] for e in entries]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        sys.exit("exported twice: " + ", ".join(sorted(dup)))

    impls = sorted({(impl, data) for _, impl, data in entries})
    fw = [
        "/* Generated by tools/gen_msw_exports.py from sdk/exports.list and",
        " * include/msw_app.h. Do not edit; run the script instead.",
        " *",
        " * Symbols are declared bare (no headers): only their addresses are taken. */",
        "#include <stddef.h>",
        "#include \"private/elf_symbol.h\"",
        "",
    ]
    for impl, data in impls:
        fw.append(f"extern const char {impl}[];" if data else f"extern void {impl}(void);")
    fw += ["", "const struct esp_elfsym msw_app_symbols[] = {"]
    for name, impl, data in entries:
        fw.append(f"    {{ \"{name}\", (void *)&{impl} }},")
    fw += ["    ESP_ELFSYM_END", "};", f"const int msw_app_symbol_count = {len(entries)};", ""]
    open(OUT_FW, "w", encoding="utf-8", newline="\n").write("\n".join(fw))

    os.makedirs(os.path.dirname(OUT_STUB), exist_ok=True)
    stub = [
        "/* Generated by tools/gen_msw_exports.py. Every symbol the StopWatch gives a",
        " * mini app, as an empty definition: sdk/build.py links each app against this",
        " * once with --no-undefined, so a call the firmware lacks fails the build. */",
        "",
    ]
    for name, _, data in entries:
        stub.append(f"char {name}[4];" if data else f"void {name}(void) {{}}")
    open(OUT_STUB, "w", encoding="utf-8", newline="\n").write("\n".join(stub) + "\n")
    print(f"{len(entries)} symbols -> {os.path.relpath(OUT_FW, ROOT)}, {os.path.relpath(OUT_STUB, ROOT)}")


if __name__ == "__main__":
    main()
